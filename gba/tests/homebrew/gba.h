/* gba.h — registros mínimos para las ROMs homebrew de prueba (código propio, MIT). */
#ifndef PGB_HOMEBREW_GBA_H
#define PGB_HOMEBREW_GBA_H
#include <stdint.h>
#define REG8(a)  (*(volatile uint8_t *)(a))
#define REG16(a) (*(volatile uint16_t *)(a))
#define REG32(a) (*(volatile uint32_t *)(a))
#define DISPCNT  REG16(0x04000000)
#define DISPSTAT REG16(0x04000004)
#define VCOUNT   REG16(0x04000006)
#define BGCNT(n) REG16(0x04000008 + 2 * (n))
#define BGHOFS(n) REG16(0x04000010 + 4 * (n))
#define BGVOFS(n) REG16(0x04000012 + 4 * (n))
#define BG2PA REG16(0x04000020)
#define BG2PB REG16(0x04000022)
#define BG2PC REG16(0x04000024)
#define BG2PD REG16(0x04000026)
#define BG2X  REG32(0x04000028)
#define BG2Y  REG32(0x0400002C)
#define BG3PA REG16(0x04000030)
#define BG3PB REG16(0x04000032)
#define BG3PC REG16(0x04000034)
#define BG3PD REG16(0x04000036)
#define BG3X  REG32(0x04000038)
#define BG3Y  REG32(0x0400003C)
#define WIN0H REG16(0x04000040)
#define WIN1H REG16(0x04000042)
#define WIN0V REG16(0x04000044)
#define WIN1V REG16(0x04000046)
#define WININ REG16(0x04000048)
#define WINOUT REG16(0x0400004A)
#define MOSAIC REG16(0x0400004C)
#define BLDCNT REG16(0x04000050)
#define BLDALPHA REG16(0x04000052)
#define BLDY  REG16(0x04000054)
#define DMA3SAD REG32(0x040000D4)
#define DMA3DAD REG32(0x040000D8)
#define DMA3CNT REG32(0x040000DC)
#define DMA0SAD REG32(0x040000B0)
#define DMA0DAD REG32(0x040000B4)
#define DMA0CNT REG32(0x040000B8)
#define IE  REG16(0x04000200)
#define IF  REG16(0x04000202)
#define IME REG16(0x04000208)
#define PAL   ((volatile uint16_t *)0x05000000)
#define VRAM  ((volatile uint16_t *)0x06000000)
#define OAM   ((volatile uint16_t *)0x07000000)
#define IRQ_HANDLER REG32(0x03007FFC)
static inline void vsync(void) { while (VCOUNT >= 160) {} while (VCOUNT < 160) {} }
#endif
